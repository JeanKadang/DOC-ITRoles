// Builds docs/SKILLS_MATRIX.md — what actually changes, technology by
// technology, when someone moves up a rung (#151, item 1).
// Zero dependencies — `npm run build-skills-matrix` (or `--dry`).
//
// This is a join, not a re-projection. Two things the repository already
// holds have never been put together:
//
//   docs/SKILLS_PROGRESSION.md   which role follows which, per domain
//   the role files themselves    which technology at which proficiency tier
//
// Crossing them answers the question a progression conversation actually
// starts with: "what would I have to get better at?" Neither source answers
// it alone, and the answer stays true without anyone maintaining it — the
// same bar the technology radar had to clear.
//
// What it deliberately does not do: propose training, name a course, or
// emit an LMS import format. No schema has been agreed, and guessing at one
// would produce a file shaped for a system nobody has specified.
'use strict';

const fs = require('fs');
const path = require('path');
const { parseProgressionLadders } = require('../viewer-logic');
const { proficiencyBullets } = require('./build-radar');

const ROOT      = path.join(__dirname, '..');
const ROLES_DIR = process.env.ROLES_DIR ? path.resolve(process.env.ROLES_DIR) : path.join(ROOT, 'Roles');
const VOCAB     = path.join(ROOT, 'data', 'technologies.json');
const LADDERS   = path.join(ROOT, 'docs', 'SKILLS_PROGRESSION.md');
const OUT       = path.join(ROOT, 'docs', 'SKILLS_MATRIX.md');
const DRY       = process.argv.includes('--dry');

// Ascending, so "higher tier" is a numeric comparison.
const TIER_RANK = { 'Awareness': 0, 'Working Knowledge': 1, 'Proficient': 2, 'Expert': 3 };

// The rungs this matrix walks. Chapter Lead and above are people-leadership
// steps whose difference is not a technology tier, so a technology delta
// would describe them poorly and is not attempted.
const RUNGS = ['Engineer', 'Senior Engineer', 'Architect'];

function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

function loadMatchers() {
  const vocab = JSON.parse(fs.readFileSync(VOCAB, 'utf8'));
  return vocab.technologies.map(t => ({
    name: t.name,
    res: t.aliases.map(a => new RegExp('(^|[^A-Za-z0-9])' + escapeRe(a) + '([^A-Za-z0-9]|$)', 'i')),
  }));
}

function roleFileFor(slug) {
  for (const dir of fs.readdirSync(ROLES_DIR)) {
    const p = path.join(ROLES_DIR, dir, slug + '.md');
    if (fs.existsSync(p)) return p;
  }
  return null;
}

// Highest tier each technology is expected at, across every role on a rung.
// A rung may hold more than one role; taking the highest describes the rung
// rather than whichever role happened to be listed first.
function rungTiers(slugs, matchers) {
  const map = new Map();
  let found = 0;
  for (const slug of slugs) {
    const file = roleFileFor(slug);
    if (!file) continue;
    found++;
    const text = fs.readFileSync(file, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
    for (const { tier, text: bullet } of proficiencyBullets(text)) {
      for (const m of matchers) {
        if (!m.res.some(re => re.test(bullet))) continue;
        const cur = map.get(m.name);
        if (cur === undefined || TIER_RANK[tier] > TIER_RANK[cur]) map.set(m.name, tier);
      }
    }
  }
  return found ? map : null;
}

function build() {
  const matchers = loadMatchers();
  const md = fs.readFileSync(LADDERS, 'utf8').replace(/^﻿/, '');
  const ladders = parseProgressionLadders(md);

  const domains = [];
  let steps = 0, empty = 0;

  for (const ladder of ladders) {
    const present = RUNGS
      .map(level => ({ level, slugs: ladder.levels[level] || [] }))
      .filter(r => r.slugs.length);
    if (present.length < 2) continue;

    const tiers = present.map(r => ({ ...r, tiers: rungTiers(r.slugs, matchers) })).filter(r => r.tiers);
    const transitions = [];

    for (let i = 0; i < tiers.length - 1; i++) {
      const from = tiers[i], to = tiers[i + 1];
      const deepens = [], adds = [];
      for (const [tech, tier] of [...to.tiers].sort((a, b) => a[0].localeCompare(b[0]))) {
        if (!from.tiers.has(tech)) { adds.push({ tech, tier }); continue; }
        const was = from.tiers.get(tech);
        if (TIER_RANK[tier] > TIER_RANK[was]) deepens.push({ tech, was, now: tier });
      }
      steps++;
      if (!deepens.length && !adds.length) empty++;
      transitions.push({ from: from.level, to: to.level, deepens, adds });
    }
    if (transitions.length) domains.push({ domain: ladder.domain, transitions });
  }
  return { domains, steps, empty };
}

function render({ domains, steps, empty }) {
  const stamp = new Date().toISOString().slice(0, 7);
  const L = [];
  L.push('# Skills matrix — what changes between rungs');
  L.push('');
  L.push('<!-- Generated by scripts/build-skills-matrix.js — do not edit by hand. -->');
  L.push('<!-- Run `npm run build-skills-matrix` after changing a ladder or a role file. -->');
  L.push('');
  L.push(`Crosses the ladders in [Career Paths & Skills Progression](SKILLS_PROGRESSION.md) with the **Technology Proficiency Levels** of the roles on each rung. ${steps} transitions across ${domains.length} domains. Generated ${stamp}.`);
  L.push('');
  L.push('## How to read it, and what it is not');
  L.push('');
  L.push('**Deepens** is a technology both rungs expect, at a higher level on the upper rung. **Adds** is one the upper rung expects and the lower one does not name at all. Where a rung holds several roles, the highest tier among them is used, so the row describes the rung rather than whichever role was listed first.');
  L.push('');
  L.push('**This is not a training plan and not an assessment.** It says what the role definitions differ on, which is a starting point for a progression conversation — not a judgement about a person, and not a course list. Turning it into either is work for whoever owns learning and development.');
  L.push('');
  L.push(`It is also only as complete as the vocabulary in \`data/technologies.json\`. A technology nobody listed is a technology this matrix cannot see. ${empty} of the ${steps} transitions show no change at all, which usually means the two role definitions describe the same technologies and differ on scope and autonomy instead — those differences are in the role files, not here.`);
  L.push('');

  for (const d of domains) {
    L.push(`## ${d.domain}`);
    L.push('');
    for (const t of d.transitions) {
      L.push(`### ${t.from} → ${t.to}`);
      L.push('');
      if (!t.deepens.length && !t.adds.length) {
        L.push('No technology difference recorded. The step is described by scope and autonomy in the role definitions.');
        L.push('');
        continue;
      }
      if (t.deepens.length) {
        L.push('| Deepens | From | To |');
        L.push('|---|---|---|');
        for (const x of t.deepens) L.push(`| ${x.tech} | ${x.was} | ${x.now} |`);
        L.push('');
      }
      if (t.adds.length) {
        L.push('| Adds | At |');
        L.push('|---|---|');
        for (const x of t.adds) L.push(`| ${x.tech} | ${x.tier} |`);
        L.push('');
      }
    }
  }
  return L.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n+$/, '') + '\n';
}

function main() {
  const data = build();
  const out = render(data);
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : null;
  const changed = existing !== out;
  if (changed && !DRY) fs.writeFileSync(OUT, out, 'utf8');
  console.log(DRY ? '[dry run]' : '[written]',
    `${data.steps} transitions across ${data.domains.length} domains · ${data.empty} with no technology change`,
    changed ? '· document differs' : '· document already current');
}

if (require.main === module) main();

module.exports = { build, render, rungTiers, RUNGS, TIER_RANK };
